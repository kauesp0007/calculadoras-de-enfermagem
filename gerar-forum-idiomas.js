function applyPairs(str, pairs, label) {
    let out = str;
    for (const [a, b] of pairs) {
        if (!out.includes(a)) {
            console.warn('  [AVISO ' + label + '] não encontrado: ' + a.slice(0, 70));
        }
        out = out.split(a).join(b);
    }
    return out;
}

