function hreflangBlock(selfCode) {
    const lines = [];
    lines.push('<link href="' + urlFor(selfCode) + '" rel="canonical"/>');
    lines.push('<link href="' + urlFor(selfCode) + '" hreflang="' + HREFLANG_CODE[selfCode] + '" rel="alternate"/>');
    lines.push('<link href="' + BASE + '/forum-enfermagem.html" hreflang="pt-br" rel="alternate"/>');
    for (const c of LANGS_ORDER) {
        if (c === selfCode) continue;
        lines.push('<link href="' + urlFor(c) + '" hreflang="' + HREFLANG_CODE[c] + '" rel="alternate"/>');
    }
    lines.push('<link href="' + BASE + '/forum-enfermagem.html" hreflang="x-default" rel="alternate"/>');
    return lines.join('\n');
}

